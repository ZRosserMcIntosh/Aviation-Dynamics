// Air-motion building blocks used by the weather fields:
//
//  - Mean wind: surface boundary layer (log law with surface roughness, or a
//    power law, or uniform), Ekman turning of the wind with height, and winds
//    aloft interpolated between reported levels above the boundary layer.
//  - Turbulence: frozen, world-space von Kármán turbulence whose intensities
//    and length scales follow MIL-HDBK-1797 / MIL-F-8785C with height:
//    anisotropic and small-scaled near the ground, isotropic aloft.
//    Mechanical (surface-layer) turbulence is generated by the actual wind
//    over the actual surface roughness; clear-air turbulence is added by
//    severity class (light / moderate / severe).
//
// Everything here is deterministic and safe for concurrent const calls.
// See docs/architecture/wind.md.
#pragma once

#include <array>
#include <cstdint>
#include <vector>

#include "avd/math.hpp"

namespace avd {

// ---------------------------------------------------------------- mean wind --

enum class WindProfile {
    Uniform,   // same wind at every height
    PowerLaw,  // U ~ z^exponent (engineering approximation)
    LogLaw,    // U = (u*/kappa) ln(z/z0): neutral surface layer
};

// A reported wind at an altitude (winds-aloft forecast, sounding, or a
// shear layer). Speed m/s; direction the wind blows FROM, rad true.
struct WindLevel {
    Real altitudeMsl = 0;
    Real speed = 0;
    Real fromDirection = 0;
};

struct BoundaryLayerParams {
    Real windSpeed = 0;              // m/s at referenceHeight AGL (the surface report)
    Real windFromDirection = 0;      // rad, true, direction the wind blows FROM
    Real referenceHeight = 10.0;     // m AGL (standard anemometer height)
    WindProfile profile = WindProfile::LogLaw;
    // Aerodynamic roughness length z0 (m): 0.0002 water, 0.03 open grass /
    // airfield, 0.1-0.25 farmland, 0.5-1 suburbs, 1-2 city centre.
    Real surfaceRoughness = 0.03;
    Real powerLawExponent = 1.0 / 7.0;  // PowerLaw only
    Real top = 600.0;                // m AGL; boundary-layer depth
    // Total turning of the wind direction from the surface to the top of
    // the boundary layer (Ekman spiral; rad, + veers = clockwise with height).
    // Over land ~ +20..30 deg in the northern hemisphere, the opposite sign
    // in the southern hemisphere; ~ 10 deg over water.
    Real veer = 0;
    // Winds above the boundary layer, by altitude (any order). The wind at
    // the boundary-layer top is blended to these; above the highest level the
    // wind stays constant. Empty: the boundary-layer-top wind holds aloft.
    std::vector<WindLevel> aloft;
};

// Von Kármán constant.
inline constexpr Real kKarman = 0.4;

class BoundaryLayer {
public:
    BoundaryLayer() = default;
    explicit BoundaryLayer(const BoundaryLayerParams& p);
    const BoundaryLayerParams& params() const { return p_; }
    // Mean horizontal air velocity (NED, m/s) at a height above the local
    // ground and the corresponding altitude MSL (winds aloft are by MSL).
    Vec3 wind(Real heightAgl, Real altitudeMsl) const;
    // d(wind)/d(height) (1/s), central difference.
    Vec3 shear(Real heightAgl, Real altitudeMsl) const;
    // Surface friction velocity u* (m/s) implied by the surface wind and
    // roughness (neutral log law), used for the mechanical turbulence.
    Real frictionVelocity() const;
    // Heading (rad) the surface wind blows TOWARD (turbulence u axis).
    Real surfaceFlowHeading() const { return p_.windFromDirection + kPi; }

private:
    Real speedFactor(Real heightAgl) const;
    BoundaryLayerParams p_;
    std::vector<WindLevel> aloft_;  // sorted by altitude
};

// ----------------------------------------------------------------- turbulence --

// Frozen, divergence-free turbulence synthesised from Fourier modes with a von
// Kármán energy spectrum (random-Fourier-mode synthesis, e.g. Kraichnan 1970).
// The field lives in world space and is advected by the mean wind, so every
// aircraft sees the same air at the same place and time. `scaleLength` is the
// longitudinal integral scale L (spectral peak k_e = 1 / (1.339 L)).
class TurbulenceField {
public:
    struct Params {
        Real intensity = 0;          // RMS of each velocity component, m/s
        Real scaleLength = 533.0;    // von Kármán integral length scale L, m
        int modes = 48;
        Real minWavelength = 4.0;    // m; shorter eddies are below airframe scale
        std::uint64_t seed = 1;
    };
    TurbulenceField() = default;
    explicit TurbulenceField(const Params& p);
    const Params& params() const { return p_; }
    bool active() const { return p_.intensity > 0 && !modes_.empty(); }
    // Velocity (NED) and gradient at a position already shifted into the
    // frozen-turbulence frame.
    void evaluate(const Vec3& x, Vec3& velocity, Mat3& gradient) const;

private:
    struct Mode {
        Vec3 k;        // wave vector, rad/m
        Vec3 dir;      // unit velocity direction, perpendicular to k
        Real amplitude;
        Real phase;
    };
    Params p_;
    std::vector<Mode> modes_;
};

// MIL-HDBK-1797 probability-of-exceedance classes: light 1e-2, moderate
// 1e-3, severe 1e-5 (W20 = 15, 30, 45 kt at low altitude).
enum class TurbulenceSeverity { None = 0, Light = 1, Moderate = 2, Severe = 3 };

struct TurbulenceParams {
    // Clear-air / convective-weather class, applied at every height.
    TurbulenceSeverity severity = TurbulenceSeverity::None;
    // Surface-layer turbulence made by the mean wind over the surface
    // roughness (sigma_w = 1.25 u*), fading out between 1000 and 2000 ft AGL.
    bool mechanical = true;
    // Additional RMS (m/s) with the same height dependence, for scenarios
    // that want a specific level. Root-sum-square with the other sources.
    Real intensity = 0;
    // Convective boundary layer (set by the weather when thermals are
    // active): w* (m/s) and its depth zi (m AGL). Lenschow et al. (1980):
    // sigma_w^2 = 1.8 w*^2 (z/zi)^(2/3) (1 - 0.8 z/zi)^2, sigma_u,v = 0.6 w*.
    Real convectiveVelocity = 0;
    Real convectiveDepth = 1500;
    Real minWavelength = 1.0;  // m; below airframe-strip scale
    int modesPerScale = 40;
    std::uint64_t seed = 1;
};

// RMS intensities and integral length scales (m/s, m) along the turbulence
// axes: u along the surface wind, v across it, w vertical.
struct TurbulenceStatistics {
    Vec3 sigma;
    Vec3 length;
};

class AtmosphericTurbulence {
public:
    AtmosphericTurbulence() = default;
    // `flowHeading`: direction (rad) the surface wind blows toward, the u
    // axis. `frictionVelocity`: surface u* (m/s) for the mechanical part.
    AtmosphericTurbulence(const TurbulenceParams& p, Real flowHeading, Real frictionVelocity);
    bool active() const { return active_; }
    const TurbulenceParams& params() const { return p_; }
    TurbulenceStatistics statistics(Real heightAgl, Real altitudeMsl) const;
    // Velocity (NED) and its gradient at `xFrozen` (position already shifted
    // into the frozen frame), whose height is heightAgl / altitudeMsl.
    void evaluate(const Vec3& xFrozen, Real heightAgl, Real altitudeMsl, Vec3& velocity, Mat3& gradient) const;

    // Bank of unit-intensity fields at integral scales kScale0 * 2^i.
    static constexpr int kScales = 10;
    static constexpr Real kScale0 = 2.0;

private:
    // Weight of each scale for a length, energy-preserving (cos/sin blend
    // of the two neighbouring scales).
    void coefficients(Real heightAgl, Real altitudeMsl, std::array<std::array<Real, kScales>, 3>& c) const;
    TurbulenceParams p_;
    Real frictionVelocity_ = 0;
    Mat3 axes_;  // columns: u, v, w axes in NED
    std::vector<TurbulenceField> bank_;
    bool active_ = false;
};

}  // namespace avd
